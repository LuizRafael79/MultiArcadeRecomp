#define COLOR0() BREG(8)
#define COLOR1() BREG(9)
#define COUNT() BREG(10)
#define INC1_X() BREG_X(11)
#define INC1_Y() BREG_Y(11)
#define INC2_X() BREG_X(12)
#define INC2_Y() BREG_Y(12)
