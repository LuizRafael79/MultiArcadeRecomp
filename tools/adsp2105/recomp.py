#!/usr/bin/env python3
"""Emit per-ROM ADSP-2105 native blocks from packed 24-bit program words.

Input is three bytes per word, big-endian, matching MAME's boot loader output
(opcode = src[0]<<16 | src[1]<<8 | src[2]). Each block validates its current
program word, allowing safe execution from boot-loaded RAM until it is changed.
"""
from __future__ import annotations

import argparse
from pathlib import Path


def emit_aot(data: bytes, output_path: Path, entry_pc: int = 0) -> tuple[int, int]:
    if len(data) % 3:
        raise ValueError("program image size must be divisible by 3 bytes")
    words = [int.from_bytes(data[i:i + 3], "big") for i in range(0, len(data), 3)]
    if len(words) > 0x4000:
        raise ValueError("ADSP-2105 program image exceeds its 14-bit PC space")
    pcs = [pc for pc, opcode in enumerate(words)
           if opcode == 0 or (opcode >> 16) in range(0x40, 0x50)
           or ((opcode >> 16) in (0x50, 0x51) and ((opcode >> 13) & 15) == 0)
           or ((opcode >> 16) == 0x0d)
           or ((opcode >> 16) in (0x22, 0x23))
           or ((opcode >> 16) in range(0x28, 0x30))
           or ((opcode >> 16) in range(0x60, 0x64))
           or ((opcode >> 16) in (0x68, 0x69, 0x70, 0x71, 0x78, 0x79))
           or ((opcode >> 16) in range(0x80, 0xa0))
           or ((opcode >> 16) in range(0x1c, 0x20))
           or (opcode >> 16) in range(0xa0, 0xc0)
           or ((opcode >> 16) == 0x0e and (opcode & 15) == 15
               and ((opcode >> 11) & 15) <= 11)
           or ((opcode >> 16) == 0x0f and ((opcode >> 11) & 15) <= 11)
           or ((opcode >> 16) in range(0x18, 0x1c)
               and ((opcode >> 4) & 0x3fff) == pc and (opcode & 15) == 15)]
    output = [
        '// Generated by tools/adsp2105/recomp.py; do not edit.',
        '#include "core/cpus/adsp2105/adsp2105.hpp"',
        '#include "core/cpus/adsp2105/dag.hpp"',
        '#include "core/cpus/adsp2105/interpreter.hpp"',
        'namespace mamerecomp::adsp2105 {',
        'static void native_write_reg0(State& s, unsigned r, std::uint16_t v) {',
        '    auto& c = s.core;',
        '    switch (r & 15) {',
        '    case 0: c.ax[0] = static_cast<std::int16_t>(v); break;',
        '    case 1: c.ax[1] = static_cast<std::int16_t>(v); break;',
        '    case 2: c.mx[0] = static_cast<std::int16_t>(v); break;',
        '    case 3: c.mx[1] = static_cast<std::int16_t>(v); break;',
        '    case 4: c.ay[0] = static_cast<std::int16_t>(v); break;',
        '    case 5: c.ay[1] = static_cast<std::int16_t>(v); break;',
        '    case 6: c.my[0] = static_cast<std::int16_t>(v); break;',
        '    case 7: c.my[1] = static_cast<std::int16_t>(v); break;',
        '    case 8: c.si = static_cast<std::int16_t>(v); break;',
        '    case 9: c.se = static_cast<std::int8_t>(v); break;',
        '    case 10: c.ar = static_cast<std::int16_t>(v); break;',
        '    case 11: c.mr = (c.mr & ~std::int64_t{0xffff}) | v; break;',
        '    case 12: c.mr = (c.mr & ~std::int64_t{0xffff0000}) | (static_cast<std::int64_t>(v) << 16); c.mr = (c.mr & 0xffffffffll) | ((v & 0x8000) ? (0xffll << 32) : 0ll); break;',
        '    case 13: c.mr = (c.mr & 0xffffffffll) | (static_cast<std::int64_t>(static_cast<std::int8_t>(v)) << 32); break;',
        '    case 14: c.sr[0] = v; break;',
        '    case 15: c.sr[1] = v; break;',
        '    }',
        '}',
    ]
    for pc in pcs:
        opcode = words[pc]
        output += [
            f'static BlockExit block_{pc:04x}(State& s, Bus& b, std::uint64_t stop) {{',
            f'    if ((s.pc & pc_mask) != 0x{pc:04x} || s.cycles >= stop) return BlockExit::Dispatch;',
            f'    if (!b.read_program24 || (b.read_program24(b.opaque, 0x{pc:04x}) & opcode_mask) != 0x{opcode:06x}) return BlockExit::NeedsInterpreter;',
            (f'    if (s.loop == (s.pc & pc_mask)) return native_nop_counter_loop(s, 0x{pc:04x}, stop);'
             if opcode == 0 else
             '    if (s.loop == (s.pc & pc_mask)) return BlockExit::NeedsInterpreter;'),
            '    s.previous_pc = s.pc & pc_mask;',
        ]
        if opcode and (opcode >> 16) in range(0x40, 0x50):
            output.append(f'    native_write_reg0(s, {opcode & 15}, 0x{(opcode >> 4) & 0xffff:04x});')
        elif opcode and (opcode >> 16) == 0x0e:
            output.append(f'    if (!native_shift(s, 0x{opcode:06x}, s.core.se)) return BlockExit::NeedsInterpreter;')
        elif opcode and (opcode >> 16) == 0x0f:
            output.append(f'    if (!native_shift(s, 0x{opcode:06x}, static_cast<std::int8_t>(0x{opcode & 0xff:02x}))) return BlockExit::NeedsInterpreter;')
        elif opcode and (opcode >> 16) in range(0xa0, 0xc0):
            dag = 'dag1_write' if (opcode >> 16) < 0xb0 else 'dag2_write'
            output += [
                f'    if (!{dag}(s, b, 0x{opcode:06x}, 0x{(opcode >> 4) & 0xffff:04x})) return BlockExit::BusFault;',
            ]
        elif opcode and ((opcode >> 16) == 0x0d
                         or (opcode >> 16) in (0x22, 0x23)
                         or (opcode >> 16) in range(0x28, 0x30)
                         or (opcode >> 16) in range(0x60, 0x64)
                         or (opcode >> 16) in (0x68, 0x69, 0x70, 0x71, 0x78, 0x79)
                         or (opcode >> 16) in range(0x80, 0xa0)
                         or (opcode >> 16) in range(0x1c, 0x20)):
            output += [
                f'    if (!native_execute_instruction(s, b, 0x{opcode:06x})) return BlockExit::NeedsInterpreter;',
                '    return s.cycles >= stop ? BlockExit::Budget : BlockExit::Dispatch;',
                '}',
            ]
            continue
        elif opcode and (opcode >> 16) in range(0x18, 0x1c):
            output += [
                f'    if (s.mstat & 0x20) return BlockExit::NeedsInterpreter;',
                f'    if (s.loop == 0x{pc:04x}) return BlockExit::NeedsInterpreter;',
                '    const auto remaining = stop - s.cycles;',
                '    s.cycles += remaining;',
                '    s.native_instructions += remaining;',
                '    return BlockExit::Budget;',
            ]
            output += ['}',]
            continue
        elif opcode:
            output += [
                '    std::uint16_t value{};',
                f'    if (!dag2_program_read(s, b, 0x{opcode:06x}, value)) return BlockExit::BusFault;',
                f'    native_write_reg0(s, {(opcode >> 4) & 15}, value);',
            ]
        output += [
            '    s.pc = (s.pc + 1) & pc_mask;',
            '    ++s.cycles;',
            '    ++s.native_instructions;',
            '    return s.cycles >= stop ? BlockExit::Budget : BlockExit::Dispatch;',
            '}',
        ]
    output += ['Block lookup(std::uint16_t pc) noexcept {', '    switch (pc & pc_mask) {']
    output += [f'    case 0x{pc:04x}: return &block_{pc:04x};' for pc in pcs]
    output += ['    default: return nullptr;', '    }', '}',
               f'std::uint16_t entry_pc() noexcept {{ return 0x{entry_pc & 0x3fff:04x}; }}',
               '} // namespace mamerecomp::adsp2105', '']
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text('\n'.join(output), encoding='utf-8')
    return len(words), len(pcs)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("program", type=Path, help="packed 24-bit ADSP program image")
    parser.add_argument("output", type=Path, help="generated C++ source path")
    parser.add_argument("--entry", type=lambda s: int(s, 0), default=0,
                        help="word-addressed reset/entry PC (default: 0)")
    args = parser.parse_args()
    try:
        words, native_entries = emit_aot(args.program.read_bytes(), args.output, args.entry)
    except ValueError as exc:
        parser.error(str(exc))
    print(f'ADSP-2105 AOT: words={words} native-entries={native_entries} interpreted-candidates={words-native_entries}')
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
