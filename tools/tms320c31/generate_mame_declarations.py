#!/usr/bin/env python3
"""Generate member declarations for the C31 MAME opcode-handler adapter."""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[2]
source = root / "core/cpus/tms320c31/mame_source/320c3x_ops.ipp"
out = root / "core/cpus/tms320c31/mame_handler_declarations.inc"
text = source.read_text()
# Remove MAME's optional floating-point reference implementation. The fixed
# integer representation below is the active MAME implementation (USE_FP=0).
text = re.sub(r"#if USE_FP.*?#endif", "", text, flags=re.S)
pattern = re.compile(
    r"^(?:inline\s+)?(void|bool|uint32_t|int32_t|double|float)\s+"
    r"tms320c3x_device::([A-Za-z0-9_]+)\s*\(([^;]*?)\)", re.M)
manual = {
    "illegal", "unimplemented", "execute_one", "update_special", "burn_cycle",
    "condition", "int2float", "float2int", "negf", "addf", "subf", "mpyf", "norm",
}
entries = []
for ret, name, args in pattern.findall(text):
    if name in manual:
        continue
    # Method signatures in the selected non-USE_FP source are unique.
    args = " ".join(args.split())
    declaration = f"    {ret} {name}({args});"
    if declaration not in entries:
        entries.append(declaration)
entries += [
    "    using indirect_handler = std::uint32_t (Interpreter::*)(std::uint32_t, std::uint8_t);",
    "    using indirect_default_handler = std::uint32_t (Interpreter::*)(std::uint32_t, std::uint8_t, std::uint32_t*&);",
    "    using opcode_handler = void (Interpreter::*)(std::uint32_t);",
    "    static const indirect_handler s_indirect_d[0x20];",
    "    static const indirect_handler s_indirect_1[0x20];",
    "    static const indirect_default_handler s_indirect_1_def[0x20];",
    "    static const opcode_handler s_tms320c3x_ops[];",
]
out.write_text("// Generated by tools/tms320c31/generate_mame_declarations.py.\n" + "\n".join(entries) + "\n")
print(f"wrote {len(entries)} declarations to {out.relative_to(root)}")
