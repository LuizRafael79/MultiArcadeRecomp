// Register and interrupt behavior is adapted from MAME's PSX RCNT device.
#include "timers.h"

#include <algorithm>
#include <utility>

namespace mamerecomp::psx {
namespace {
constexpr uint32_t STOP = 0x001;
constexpr uint32_t RESET = 0x004;
constexpr uint32_t COUNT_TARGET = 0x008;
constexpr uint32_t IRQ_TARGET = 0x010;
constexpr uint32_t IRQ_OVERFLOW = 0x020;
constexpr uint32_t REPEAT = 0x040;
constexpr uint32_t REACHED_TARGET = 0x800;
constexpr uint32_t REACHED_OVERFLOW = 0x1000;
}

uint32_t RootTimers::read(unsigned offset)
{
    Timer &t = timers_[(offset / 4) % 3];
    const uint32_t value = peek(offset);
    if ((offset % 4) == 1) t.mode &= ~(REACHED_TARGET | REACHED_OVERFLOW);
    return value;
}

uint32_t RootTimers::peek(unsigned offset) const
{
    const Timer &t = timers_[(offset / 4) % 3];
    switch (offset % 4) {
    case 0: return t.count & 0xffff;
    case 1: return t.mode;
    case 2: return t.target & 0xffff;
    default: return 0;
    }
}

void RootTimers::write(unsigned offset, uint32_t value)
{
    Timer &t = timers_[(offset / 4) % 3];
    switch (offset % 4) {
    case 0: t.count = value & 0xffff; t.phase = 0; break;
    case 1:
        t.count = (value & RESET) ? 0 : t.count;
        t.mode = (value & ~(RESET | STOP | REACHED_TARGET | REACHED_OVERFLOW)) |
                 (t.mode & (REACHED_TARGET | REACHED_OVERFLOW));
        t.phase = 0;
        t.irq_fired = false;
        break;
    case 2: t.target = value & 0xffff; break;
    default: break;
    }
    recompute_next_event();
}

void RootTimers::recompute_next_event()
{
    uint64_t delay = UINT64_MAX;
    for (unsigned i = 0; i < timers_.size(); ++i) {
        const Timer &t = timers_[i];
        if (t.mode & STOP) continue;
        uint64_t divider = 1;
        if (i == 0 && (t.mode & 0x100)) divider = 5;
        if (i == 1 && (t.mode & 0x100)) divider = 2150;
        if (i == 2 && (t.mode & 0x200)) divider = 8;
        const uint64_t count = t.count & 0xffffu;
        const uint64_t to_overflow = 0x10000u - count;
        uint64_t ticks = to_overflow;
        const uint64_t target = t.target & 0xffffu;
        if (target) {
            const uint64_t to_target = target > count
                ? target - count
                : to_overflow + target;
            ticks = std::min(ticks, to_target);
        }
        const uint64_t input_clocks = ticks * divider > t.phase
            ? ticks * divider - t.phase : 1;
        const uint64_t cycles = std::max<uint64_t>(1, (input_clocks + 1) / 2);
        delay = std::min(delay, cycles);
    }
    next_event_cycle_ = delay == UINT64_MAX ? UINT64_MAX : elapsed_cycles_ + delay;
}

void RootTimers::advance(uint64_t cycles)
{
    if (cycles <= elapsed_cycles_) return;
    uint64_t delta = cycles - elapsed_cycles_;
    elapsed_cycles_ = cycles;
    for (unsigned i = 0; i < timers_.size(); ++i) {
        Timer &t = timers_[i];
        if (t.mode & STOP) continue;
        uint64_t divider = 1;
        if (i == 0 && (t.mode & 0x100)) divider = 5;
        if (i == 1 && (t.mode & 0x100)) divider = 2150;
        if (i == 2 && (t.mode & 0x200)) divider = 8;
        const uint64_t clocks = delta * 2 + t.phase;
        const uint64_t ticks = clocks / divider;
        t.phase = clocks % divider;
        if (!ticks) continue;

        // Collapse ordinary counter increments into arithmetic. MAME updates
        // the RCNT device from scheduler time; calling tick() once or twice
        // for each CPU instruction made long interpreter runs scale poorly.
        // Preserve target/overflow flags and the IRQ edge generated by tick().
        const uint64_t initial = t.count & 0xffffu;
        const bool count_to_target = (t.mode & COUNT_TARGET) != 0;
        const uint64_t target = t.target & 0xffffu;
        bool reached_target = false;
        bool reached_overflow = false;

        if (count_to_target && target != 0 && initial < target) {
            const uint64_t first_target = target - initial;
            if (ticks < first_target) {
                t.count = static_cast<uint32_t>(initial + ticks);
                continue;
            }
            reached_target = true;
            t.count = static_cast<uint32_t>((ticks - first_target) % target);
        } else if (count_to_target && target != 0) {
            const uint64_t to_overflow = 0x10000u - initial;
            const uint64_t first_target = to_overflow + target;
            reached_overflow = ticks >= to_overflow;
            if (ticks < first_target) {
                t.count = static_cast<uint32_t>((initial + ticks) & 0xffffu);
            } else {
                reached_target = true;
                t.count = static_cast<uint32_t>((ticks - first_target) % target);
            }
        } else {
            const uint64_t to_overflow = 0x10000u - initial;
            reached_overflow = ticks >= to_overflow;
            if (target != 0) {
                const uint64_t to_target = target > initial
                    ? target - initial
                    : to_overflow + target;
                reached_target = ticks >= to_target;
            }
            t.count = static_cast<uint32_t>((initial + ticks) & 0xffffu);
        }

        if (reached_target) t.mode |= REACHED_TARGET;
        if (reached_overflow) t.mode |= REACHED_OVERFLOW;
        const bool request =
            (reached_target && (t.mode & IRQ_TARGET)) ||
            (reached_overflow && (t.mode & IRQ_OVERFLOW));
        if (request && ((t.mode & REPEAT) || !t.irq_fired)) {
            t.irq_fired = true;
            if (irq_) irq_(4 + i, true);
        }
    }
    recompute_next_event();
}

} // namespace mamerecomp::psx
